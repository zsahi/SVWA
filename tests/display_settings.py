"""Read-only browser checks for shared SQL display controls. Requires Playwright."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = os.environ.get('SVWA_URL', 'http://127.0.0.1:8888')

with sync_playwright() as playwright:
    browser = playwright.chromium.launch(channel='chrome', headless=True)
    context = browser.new_context(viewport={'width': 1440, 'height': 1000})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE + '/labs/union.php')
    query = page.get_by_label('Display SQL queries', exact=True)
    diagnostics = page.get_by_label('Display database errors', exact=True)
    expect(query).not_to_be_checked()
    expect(diagnostics).not_to_be_checked()
    page.locator('#entry').fill('Canvas')
    query.check()
    expect(query).to_be_enabled()
    expect(page.locator('.display-settings-status')).to_have_text('')
    expect(page.locator('#entry')).to_have_value('Canvas')
    diagnostics.check()
    expect(diagnostics).to_be_enabled()
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('pre.panel')).to_contain_text("name LIKE '%Canvas%'")
    expect(page.locator('.result')).to_contain_text('Canvas Backpack')
    page.locator('#entry').fill("'")
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('.result')).to_contain_text('SQLSTATE')
    diagnostics.uncheck()
    expect(diagnostics).to_be_enabled()
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('.result')).to_have_text('Request could not be completed.')
    page.goto(BASE + '/settings.php')
    expect(query).to_have_count(0)
    expect(diagnostics).to_have_count(0)
    expect(page.locator('form.settings input[type=checkbox]')).to_have_count(0)
    page.locator('#submission').select_option('json')
    expect(page.locator('#submission')).to_be_enabled()
    expect(query).to_have_count(0)
    page.goto(BASE + '/labs/union.php')
    expect(query).to_be_checked()
    expect(diagnostics).not_to_be_checked()
    page.locator('#entry').fill('Desk')
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('.result')).to_contain_text('Desk Lamp')
    query.uncheck()
    expect(query).to_be_enabled()
    page.get_by_role('button', name='Search', exact=True).click()
    expect(page.locator('pre.panel')).to_have_count(0)
    for path in ['/labs/union.php', '/labs/numeric.php', '/labs/boolean.php', '/labs/time.php', '/labs/order.php']:
        page.goto(BASE + path)
        expect(query).to_be_visible()
        expect(diagnostics).to_be_visible()
        expect(query).not_to_be_checked()
    for path in ['/', '/settings.php', '/login.php', '/labs/html.php', '/labs/ssrf.php']:
        page.goto(BASE + path)
        expect(query).to_have_count(0)
        expect(diagnostics).to_have_count(0)
    assert context.request.post(BASE + '/display-settings.php', form={'token':'invalid','show_query':'1','show_errors':'1'}).status == 403
    assert context.request.get(BASE + '/display-settings.php').status == 405
    page.goto(BASE + '/labs/union.php')
    out = Path(os.environ.get('TEMP', '.'))
    page.screenshot(path=str(out / 'svwa-header-desktop.png'))
    page.set_viewport_size({'width': 390, 'height': 844})
    page.locator('.topbar').scroll_into_view_if_needed()
    expect(query).to_be_visible()
    expect(diagnostics).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(out / 'svwa-header-mobile.png'))
    assert not errors, errors
    browser.close()
    print('PASS: shared header, persistence, query/errors, JSON navigation, preserved input, settings, mobile layout, endpoint validation.')
